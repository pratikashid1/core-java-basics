package Arrays.MultiArray.twoDArray;

public class twoD {
    public static void main(String[] args) {

        // Declaring array
        int[][] arr;

        // Initializing array
        arr = new int[1][3];

        //Accessing values
        arr[0][0] = 3;
        arr[0][1] = 5;
        arr[0][2] = 7;

        // Displaying Values
        System.out.println("arr[0][0] = " + arr[0][0]);
        System.out.println("arr[0][1] = " + arr[0][1]);
        System.out.println("arr[0][2] = " + arr[0][2]);
    }
}
